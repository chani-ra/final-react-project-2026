export function getCleanOptions(options = []) {
  if (!Array.isArray(options)) return [];

  return options.map((option) => String(option || "").trim()).filter(Boolean);
}

export function getLevelLabel(level) {
  const labels = {
    beginner: "מתחילים",
    intermediate: "בינוני",
    advanced: "מתקדמים",
  };

  return labels[level] || level || "לא צוינה";
}

